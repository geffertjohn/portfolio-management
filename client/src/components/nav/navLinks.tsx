/**
 * The navigation tree, as data.
 *
 * Lifted out of `Layout.tsx` (audit §22), which carried ~400 lines of inline
 * SVG around a tree rendered twice — once as a desktop dropdown and once as a
 * mobile accordion. Keeping the arrays here means the two renderings cannot
 * disagree about what is in the menu, and the icons stop burying the layout.
 *
 * Icons are inline SVG on purpose: no icon dependency, and each is a few
 * elements. They are the `icon` field so a renderer never has to know which
 * glyph belongs to which route.
 */
