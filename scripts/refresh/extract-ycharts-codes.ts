/**
 * extract-ycharts-codes.ts — build the checked-in YCharts code vocabulary.
 *
 *   npx vite-node scripts/refresh/extract-ycharts-codes.ts -- ~/Downloads/YCharts_Excel_Reference-2.xlsx
 *
 * WHY THIS EXISTS. The sheet header in the YCharts workbook does TWO jobs: it is
 * the metric code `YCP()`/`YCI()` reads AND the DB column name the importers map
 * to. Nothing checked the first job, so three columns shipped fetching an
 * undocumented string — `over_30_years_maturity_bond_exposure` and
 * `effective_maturity` are the metric's DISPLAY NAMES, not codes, and
 * `maturity_other_generic` was simply never requested. They returned a figure
 * for most funds and nothing for a few, which is how they surfaced: a review
 * needed DHRIX's maturity profile and found a null.
 *
 * The reference workbook is the authority and it lives in ~/Downloads, outside
 * the repo. This lifts its vocabulary into a file a test can read offline, the
 * same way `schemaContract.test.ts` reads `supabase/schema.sql` rather than
 * opening a connection.
 *
 * WHICH TABS, AND WHY IT MATTERS THAT THEY ARE RECORDED SEPARATELY.
 *
 *  - ONE SHEET SERVES BOTH mutual funds and ETFs, so a code present for only
 *    one of them errors on every row of the other type. The fund codes must sit
 *    in the INTERSECTION, which is only checkable if membership is per-tab.
 *  - METRICS AND INFO ARE NOT INTERCHANGEABLE. A code from an `| Info` tab
 *    returns ERR under `YCP` and vice versa, and the Securities sheet carries
 *    both families (C..N are `YCI`, O rightward `YCP`).
 *
 * Regenerate it when the add-in is updated; the header records which file and
 * mtime it came from so a stale vocabulary is visible rather than assumed.
 */
import * as XLSX from 'xlsx'
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { homedir } from 'node:os'

/** tab → short flag written into the file. */
const TABS: Record<string, string> = {
  'Mutual Fund | Metrics': 'mf-m',
  'Mutual Fund | Info': 'mf-i',
  'ETF & CEF | Metrics': 'etf-m',
  'ETF & CEF | Info': 'etf-i',
  'Model Portfolio | Metrics': 'mp-m',
  'Model Portfolio | Info': 'mp-i',
}

const OUT = 'scripts/refresh/ycharts-codes.txt'

/**
 * A cell is a CODE when it is entirely lowercase snake_case. The reference
 * puts the display name ("Effective Maturity") and the code
 * ("effective_maturity_generic") in adjacent cells of the same row, so case is
 * what separates them — and conflating the two is the defect this guards.
 */
function isCode(s: string): boolean {
  return /^[a-z0-9_]+$/.test(s) && s.includes('_') && s.length > 3
}

function main(): void {
  const arg = process.argv.slice(2).find((a) => a.endsWith('.xlsx'))
  if (!arg) throw new Error('pass the reference workbook path')
  const path = arg.startsWith('~') ? arg.replace('~', homedir()) : arg

  const wb = XLSX.read(readFileSync(path), { type: 'buffer' })
  const flagsFor = new Map<string, Set<string>>()
  const missingTabs: string[] = []

  for (const [tab, flag] of Object.entries(TABS)) {
    const ws = wb.Sheets[tab]
    if (!ws) { missingTabs.push(tab); continue }
    const rows = XLSX.utils.sheet_to_json<unknown[]>(ws, { header: 1, raw: true, defval: null })
    for (const row of rows) {
      for (const cell of row ?? []) {
        if (typeof cell !== 'string') continue
        const t = cell.trim()
        if (!isCode(t)) continue
        if (!flagsFor.has(t)) flagsFor.set(t, new Set())
        flagsFor.get(t)!.add(flag)
      }
    }
  }
  // A missing tab would silently shrink the vocabulary and turn the test from a
  // guard into a rubber stamp, so it is fatal rather than a warning.
  if (missingTabs.length > 0) throw new Error(`tabs not found: ${missingTabs.join(', ')}`)
  if (flagsFor.size < 1000) throw new Error(`only ${flagsFor.size} codes — the extract looks wrong`)

  const stat = statSync(path)
  const lines = [
    '# GENERATED by scripts/refresh/extract-ycharts-codes.ts — do not edit by hand.',
    '#',
    '# The YCharts metric/info code vocabulary, lifted from the add-in reference',
    '# workbook so a test can check our sheet headers against it offline.',
    '#',
    `# source: ${path.split('/').pop()}  (mtime ${stat.mtime.toISOString().slice(0, 10)})`,
    `# codes:  ${flagsFor.size}`,
    '#',
    '# One code per line, then the tabs it appears on:',
    '#   mf-m / mf-i    Mutual Fund   | Metrics / Info',
    '#   etf-m / etf-i  ETF & CEF     | Metrics / Info',
    '#   mp-m / mp-i    Model Portfolio | Metrics / Info',
    '#',
    '# A FUND CODE MUST BE IN BOTH mf-* AND etf-*: one sheet serves both types,',
    '# so a code present for only one errors on every row of the other. And a',
    '# Metrics code returns ERR under YCI and vice versa, so the families are',
    '# recorded separately rather than merged.',
    '',
    ...[...flagsFor.keys()].sort().map((c) => `${c}\t${[...flagsFor.get(c)!].sort().join(' ')}`),
  ]
  writeFileSync(OUT, lines.join('\n') + '\n')
  console.log(`wrote ${OUT}: ${flagsFor.size} codes from ${Object.keys(TABS).length} tabs`)
}

main()
