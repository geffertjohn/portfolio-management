#!/usr/bin/env node
/**
 * generate-plists.mjs — emit one LaunchAgent plist per scheduled committee job.
 *
 * The schedule lives HERE, in git, and the plists are generated artifacts kept
 * beside it so a change is reviewable in a diff. Run this, then install.sh.
 *
 *   node scripts/scheduled-jobs/generate-plists.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(HERE, 'launchagents')
const REPO = path.resolve(HERE, '../..')
const HOME = os.homedir()

/**
 * Times are staggered 15-30 minutes apart because a run takes 12-15 minutes and
 * two jobs sharing the Supabase/FMP connectors at once is asking for trouble.
 *
 * Under the app scheduler, pre- and post-earnings both nominally fired at 09:30
 * and were separated only by random jitter — which is not a schedule, it is a
 * coin flip. The ordering that MATTERS is at-risk-review before
 * post-earnings-brief: the brief reports any same-day at-risk change, and there
 * is only ever one brief per print.
 */
const JOBS = [
  { id: 'weekly-risk-report',    days: [1],           hour: 7,  minute: 15 },
  { id: 'reviews-due-digest',    days: [1],           hour: 7,  minute: 40 },
  { id: 'at-risk-review',        days: [1,2,3,4,5],   hour: 9,  minute: 0  },
  { id: 'post-earnings-brief',   days: [1,2,3,4,5],   hour: 9,  minute: 30 },
  { id: 'pre-earnings-brief',    days: [1,2,3,4,5],   hour: 9,  minute: 45 },
  { id: 'earnings-call-summary', days: [1,2,3,4,5],   hour: 10, minute: 0  },
  { id: 'watchlist-research',    days: [1,2,3,4,5],   hour: 10, minute: 20 },
]

const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;')

function plist({ id, days, hour, minute }) {
  const cal = days.map((d) =>
    `    <dict><key>Weekday</key><integer>${d}</integer>` +
    `<key>Hour</key><integer>${hour}</integer>` +
    `<key>Minute</key><integer>${minute}</integer></dict>`).join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  LaunchAgent for the "${id}" committee job. GENERATED by
  scripts/scheduled-jobs/generate-plists.mjs — edit the JOBS table there.

  An AGENT, not a Daemon: \`claude\` authenticates with the stored claude.ai
  login, which lives in the login keychain and is reachable only from the
  logged-in GUI session. A daemon has none and would fail auth.

  RunAtLoad is false so installing this does not immediately fire a run.

  launchd does NOT wake a sleeping Mac. The Studio is already woken for the
  05:30 YCharts refresh by \`pmset repeat wakeorpoweron\`, which covers these
  later jobs too. A reboot still stops at the FileVault unlock screen with no
  user session — accepted, same as the refresh; the job_runs heartbeat is what
  surfaces a missed day.
-->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.john.pm-${id}</string>

  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${xml(path.join(REPO, 'scripts/scheduled-jobs/run-job.sh'))}</string>
    <string>${id}</string>
  </array>

  <key>StartCalendarInterval</key>
  <array>
${cal}
  </array>

  <key>RunAtLoad</key>
  <false/>

  <!-- launchd's own capture, for failures before run-job.sh can log. -->
  <key>StandardOutPath</key>
  <string>${xml(path.join(HOME, 'portfolio-jobs/logs/launchd-' + id + '.out'))}</string>
  <key>StandardErrorPath</key>
  <string>${xml(path.join(HOME, 'portfolio-jobs/logs/launchd-' + id + '.err'))}</string>

  <!--
    launchd's default PATH does not include ~/.local/bin, where the \`claude\`
    binary lives. Without this the job dies with "command not found" and only
    the .err file would ever say so.
  -->
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>${xml(path.join(HOME, '.local/bin'))}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
</dict>
</plist>
`
}

mkdirSync(OUT, { recursive: true })
for (const job of JOBS) {
  const f = path.join(OUT, `com.john.pm-${job.id}.plist`)
  writeFileSync(f, plist(job))
  const when = job.days.length === 1 ? 'Mondays' : 'weekdays'
  console.log(`✓ ${job.id.padEnd(22)} ${when} at ${String(job.hour).padStart(2,'0')}:${String(job.minute).padStart(2,'0')}`)
}
console.log(`\n${JOBS.length} plists written to ${OUT}`)
